export type LifeStage = 'child' | 'teen' | 'youth' | 'settle' | 'middle' | 'mature' | 'senior';

export function lifeStage(startAge: number): LifeStage {
  const mid = startAge + 5;
  if (mid < 13) return 'child';
  if (mid < 20) return 'teen';
  if (mid < 30) return 'youth';
  if (mid < 40) return 'settle';
  if (mid < 50) return 'middle';
  if (mid < 60) return 'mature';
  return 'senior';
}

