export function glossOf(term: string): { key: string; desc: string } | null {
  const key = GLOSSARY[term] ? term : ALIAS[term];
  return key && GLOSSARY[key] ? { key, desc: GLOSSARY[key] } : null;
}

const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const TERMS = [...new Set([...Object.keys(GLOSSARY), ...Object.keys(ALIAS)])]
  // 한 글자짜리나 너무 흔한 낱말은 본문에서 자동으로 찾지 않는다
  .filter((t) => t.length >= 2 && !['사주', '팔자', '정기', '귀인', '중화'].includes(t))
  .sort((a, b) => b.length - a.length);
const RE = new RegExp(TERMS.map(esc).join('|'), 'g');

const isHangul = (ch: string | undefined) => !!ch && ch >= '가' && ch <= '힣';

/** 일상어로 쓰인 경우를 거른다 */
function skip(term: string, text: string, i: number): boolean {
  const prev = text[i - 1];
  if (isHangul(prev)) return true;
  const after = text.slice(i + term.length, i + term.length + 6);
  const before = text.slice(Math.max(0, i - 2), i);
  switch (term) {
    case '상관':
      return /^(없|있|하|관계|이 없|도 없|마)/.test(after);
    case '식상':
      return /^(하|한|해)/.test(after);
    case '세운':
      return /^(다|지|뒤| 뒤| 후| 다음| 계획| 목표| 것| 사람| 기준| 마감| 루틴| 원칙| 대로| 만큼| 덕)/.test(after) || /[을를] $/.test(before);
    case '일주':
      return after.startsWith('일');
    case '통근':
      return /^( 시간| 버스| 길| 거리|길|하|해)/.test(after);
    case '일간':
      return after.startsWith('지');
    case '월간':
      return /^(지| 계획| 목표| 운세| 리포트| 일정)/.test(after);
    case '도화':
      return after.startsWith('지');
    case '일지':
      return /^(를 쓰|를 적|에 적|에 쓰|장)/.test(after) || /(업무|감사|운동|육아|독서|공부) $/.test(text.slice(Math.max(0, i - 3), i));
    case '지지':
      return /^(하|해|받|자|율|층|부진)/.test(after);
    case '관성':
      return /^(의 법칙|처럼 굴)/.test(after);
    case '인성':
      return /^(이 좋|이 바르|교육|검사)/.test(after);
    default:
      return false;
  }
}

export type GlossPart = string | { key: string; text: string };

/** 글을 [일반 글, 용어, 일반 글, …]으로 나눈다. 같은 용어는 처음 한 번만 표시한다. */
export function glossSplit(text: string, max = 8, seen: Set<string> = new Set()): GlossPart[] {
  const out: GlossPart[] = [];
  let last = 0;
  let n = 0;
  RE.lastIndex = 0;
  for (let m = RE.exec(text); m; m = RE.exec(text)) {
    const term = m[0];
    const hit = glossOf(term);
    if (!hit || seen.has(hit.key) || skip(term, text, m.index)) continue;
    if (n >= max) break;
    seen.add(hit.key);
    if (m.index > last) out.push(text.slice(last, m.index));
    out.push({ key: hit.key, text: term });
    last = m.index + term.length;
    n++;
  }
  if (last < text.length) out.push(text.slice(last));
  return out;
}
